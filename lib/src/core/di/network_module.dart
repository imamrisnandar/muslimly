@module
abstract class NetworkModule {
  @lazySingleton
  Dio get dio {
    final dio = Dio(
      BaseOptions(
        baseUrl: '${AppUrls.baseApi}/',
        connectTimeout: const Duration(seconds: 30),
        receiveTimeout: const Duration(seconds: 30),
        headers: {
          'Content-Type': 'application/json',
          'Accept': 'application/json',
          'X-Device-ID': kIsWeb
              ? 'web'
              : Platform.isAndroid
              ? 'android'
              : 'ios',
        },
      ),
    );

    if (!kIsWeb) {
      _configureSslPinning(dio);
    }

    if (kDebugMode) {
      dio.interceptors.add(
        LogInterceptor(
          requestBody: true,
          responseBody: false,
          requestHeader: false,
          responseHeader: false,
        ),
      );
    }

    return dio;
  }
}

void _configureSslPinning(Dio dio) {
  (dio.httpClientAdapter as IOHttpClientAdapter).createHttpClient = () {
    // Debug: standard validation only (allows Charles/Proxyman intercept)
    if (kDebugMode) {
      return HttpClient()
        ..badCertificateCallback =
            (X509Certificate cert, String host, int port) => false;
    }

    // Release: trust E7 intermediate CA + system roots
    final certBytes = utf8.encode(_letsEncryptE7Pem);
    final context = SecurityContext(withTrustedRoots: true);
    try {
      context.setTrustedCertificatesBytes(certBytes);
    } catch (_) {
      // Already in system store — safe to continue
    }

    return HttpClient(context: context)
      ..badCertificateCallback =
          (X509Certificate cert, String host, int port) => false;
  };
}
